export function Icon({
  name,
  size = 20,
  className = "",
  strokeWidth = 1.75,
  gradient = false,
  animated = false,
  title,
}: IconProps) {
  const uid = useId().replace(/:/g, "");
  const gid = `g-${uid}`;

  const stroke = gradient ? `url(#${gid})` : "currentColor";

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={stroke}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`uicon ${animated ? "animated" : ""} ${className}`}
      role={title ? "img" : undefined}
      aria-label={title}
      style={{ flexShrink: 0 }}
    >
      {gradient && (
        <defs>
          <linearGradient id={gid} x1="0" y1="0" x2="1" y2="1">
            <stop offset="0%" stopColor="#3b82f6" />
            <stop offset="100%" stopColor="#1e3a8a" />
          </linearGradient>
        </defs>
      )}
      {title && <title>{title}</title>}
      {PATHS[name] ?? FALLBACK}
    </svg>
  );
}

